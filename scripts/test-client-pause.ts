import assert from "node:assert/strict";
import { buildAdminReports } from "@/lib/executive/admin-reports";
import { defaultPauseMonth, isPauseOnlyChange, validatePause } from "@/lib/client-pipeline/pause";
import { santiagoMonthKey } from "@/lib/client-pipeline/agenda-urgency";
import { advancePipelineStatus } from "@/lib/client-pipeline/constants";
import { countExecutiveAgendaStats } from "@/lib/client-pipeline/agenda-stats";
import { clientGestionBuckets } from "@/lib/client-pipeline/client-gestion-filter";
import { nextFollowUpActions } from "@/lib/client-pipeline/follow-up";
import { buildEmptyClientProfile } from "@/lib/client-profile/constants";
import type { UserRecord } from "@/types/user";

const now = new Date("2026-11-02T16:00:00Z");
for (const month of ["", "2026-13", "2027-01-01", "2026-11", "2026-10"]) assert.throws(() => validatePause(month, "Motivo", now));
assert.throws(() => validatePause("2027-01", " ", now));
assert.deepEqual(validatePause("2027-01", " Anualidad ", now), { month: "2027-01", reason: "Anualidad" });
assert.equal(santiagoMonthKey("2026-12-01T02:59:59Z"), "2026-11");
assert.equal(santiagoMonthKey("2026-12-01T03:00:00Z"), "2026-12");
const pause = { pipelineStatus: "PAUSADO" as const, manualStatusChange: true, statusChangeNote: "Motivo", pauseUntilMonth: "2027-01", pauseReason: "Motivo" };
assert.equal(isPauseOnlyChange(pause, "NUEVO"), true);
assert.equal(isPauseOnlyChange({ ...pause, pipelineNotes: "No permitido" }, "NUEVO"), false);
assert.equal(isPauseOnlyChange({ ...pause, clientProfile: { firstNames: "Cambio no permitido" } }, "NUEVO"), false);
assert.equal(isPauseOnlyChange({ pipelineStatus: "PENDIENTE", manualStatusChange: true, statusChangeNote: "Reactivar" }, "PAUSADO"), true);
assert.equal(isPauseOnlyChange({ pipelineStatus: "CONTACTADO", manualStatusChange: true, statusChangeNote: "Cambio" }, "PAUSADO"), false);
for (const status of ["CONTACTADO", "NO_CONTESTA", "EN_SEGUIMIENTO", "RECEPCIONADO"] as const) assert.equal(advancePipelineStatus("PAUSADO", status), "PAUSADO");
assert.equal(advancePipelineStatus("PENDIENTE", "CONTACTADO"), "CONTACTADO");
assert.equal(advancePipelineStatus("ENVIADO_ISAPRE", "CONTACTADO"), "ENVIADO_ISAPRE");
const client = { id: "paused", fullName: "Cliente", createdAt: now.toISOString(), assignedExecutiveId: "owner", pipelineStatus: "PAUSADO", nextCallAt: "2026-11-01T15:00:00Z", confirmationCallAt: "2026-11-01T15:00:00Z", reminderAt: now.toISOString(), clientProfile: { ...buildEmptyClientProfile(), anualidad: true, anualidadExpiresMonth: "2026-10" } } as UserRecord;
const stats = countExecutiveAgendaStats({ clients: [client], executiveId: "owner", isAdmin: false, now });
assert.equal(Object.values(stats.items).flat().length, 0, "Paused clients never produce agenda/annuality items");
assert.equal(clientGestionBuckets(client).size, 0);
assert.deepEqual(nextFollowUpActions(client, now), []);
const pending = { ...client, pipelineStatus: "PENDIENTE" as const, pendingSince: now.toISOString() };
assert.equal(countExecutiveAgendaStats({ clients: [pending], executiveId: "owner", isAdmin: false, now }).items.dueToday.filter(row => row.kind === "pending_client").length, 1);
assert.equal(countExecutiveAgendaStats({ clients: [pending], executiveId: "other", isAdmin: false, now }).items.dueToday.length, 0);
assert.equal(defaultPauseMonth({ ...client, pipelineStatus: "NUEVO", clientProfile: { ...client.clientProfile!, anualidadExpiresMonth: "2027-03" } }, now), "2027-03");
assert.equal(defaultPauseMonth({ ...client, pipelineStatus: "NUEVO", clientProfile: { ...client.clientProfile!, anualidad: false } }, now), "2026-12");
console.log("OK pausa: validación mensual, permisos limitados, exclusión de agenda/anualidad, Pendiente y conservación del embudo.");

const report = buildAdminReports({ clients: [client], period: { kind: "month", monthKey: "2026-11" }, selectedExecutiveIds: [] });
assert.equal(report.totals.pipeline.PAUSADO, 1);
assert.equal(report.totals.firstContactDone, 0, "Pausing never invents a completed contact");
assert.equal(report.totals.zoomOverdue + report.totals.zoomToday + report.totals.confirmOverdue + report.totals.confirmToday, 0);
